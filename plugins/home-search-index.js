/* ------------------------------------------------------------------
 * 自定义插件: 为首页「即时搜索下拉」提供一份轻量的文档元数据索引。
 *
 * 为什么需要它:
 *   useAllDocsData() 返回的 docs 是精简元数据(只有 id / path / sidebar),
 *   不含 title / description / permalink —— 不足以渲染搜索结果。
 *   而 allContentLoaded 能拿到所有 docs 插件的完整 DocMetadata。
 *
 * 做法:
 *   收录「在侧边栏导航中可见」的文档(孤儿文档——目录里有文件但不在任何
 *   sidebar 里——不收录, 否则会检索到导航里点不到的页面)。
 *   所有产品的所有版本(含历史版本)都收录, 每项标注 versionPath / versionLabel /
 *   isLast 等版本信息:
 *   - 前端在「某产品某版本」文档页内搜索时, 用 versionPath 精确限定到该版本;
 *   - 前端在全局搜索(首页/查看全部)时, 只取 isLast(最新版本)去重, 避免 v1/v2
 *     内容重复出现。
 *   全站约数百篇文档, 精简后体积几十 KB, 完全可接受。
 * ------------------------------------------------------------------ */

/* 收集某版本侧边栏中引用的文档 id(sidebar 为 NormalizedSidebars)。
   返回: { docIds: Set<string>, autoDirs: string[] }
   - docIds: 显式通过 type:'doc'/'ref' 引用的文档 id;
   - autoDirs: autogenerated 侧边栏的目录前缀(docs.sourceDirName 归属其下则视为可见)。
   说明: sidebars 不存在或为空时(该版本没配导航)视为全空, 不收录任何文档。 */
function collectNavigableDocIds(sidebars) {
  const docIds = new Set();
  const autoDirs = [];
  function walkItem(item) {
    if (!item || typeof item.type !== 'string') {
      return;
    }
    switch (item.type) {
      case 'doc':
      case 'ref':
        if (item.id) {
          docIds.add(item.id);
        }
        return;
      case 'autogenerated':
        if (item.dirName) {
          autoDirs.push(item.dirName);
        }
        return;
      case 'category':
        // 分类自身可作为链接指向某文档
        if (item.link && item.link.type === 'doc' && item.link.id) {
          docIds.add(item.link.id);
        }
        // 递归子项
        (item.items || []).forEach(walkItem);
        return;
      case 'link':
      case 'html':
      default:
        return;
    }
  }
  Object.values(sidebars || {}).forEach((items) => {
    (items || []).forEach(walkItem);
  });
  return {docIds, autoDirs};
}

/* 某文档是否在侧边栏导航中可见 */
function isNavigable(doc, nav) {
  if (nav.docIds.has(doc.id)) {
    return true;
  }
  // autogenerated 目录: sourceDirName 为该目录或其子目录
  for (const dir of nav.autoDirs) {
    const norm = (dir || '').replace(/\/+$/, '');
    if (norm === '.' || norm === '') {
      return true;
    }
    if (doc.sourceDirName === norm || doc.sourceDirName.startsWith(norm + '/')) {
      return true;
    }
  }
  return false;
}

module.exports = function homeSearchIndexPlugin() {
  return {
    name: 'home-search-index',

    async allContentLoaded({allContent, actions}) {
      const items = [];
      const seen = new Set();

      // allContent 是两层: { [pluginName]: { [pluginId]: content } }
      Object.entries(allContent || {}).forEach(([, byPluginId]) => {
        Object.values(byPluginId || {}).forEach((content) => {
          const versions = content?.loadedVersions;
          if (!Array.isArray(versions)) {
            return; // 非 docs 插件(theme / pages / 搜索等), 跳过
          }
          // 收录所有版本: 每项标注版本信息, 供前端按「产品+版本」限定或在全局视图去重
          versions.forEach((version) => {
            // 只收录侧边栏导航中可见的文档(过滤孤儿文档)
            const nav = collectNavigableDocIds(version.sidebars);
            (version.docs || []).forEach((doc) => {
              if (
                !doc?.permalink ||
                doc.unlisted ||
                doc.draft ||
                doc.frontMatter?.draft
              ) {
                return;
              }
              if (!isNavigable(doc, nav)) {
                return; // 不在导航侧边栏里, 跳过
              }
              if (seen.has(doc.permalink)) {
                return;
              }
              seen.add(doc.permalink);
              items.push({
                title: doc.title || doc.frontMatter?.title || '',
                desc: doc.description || doc.frontMatter?.description || '',
                permalink: doc.permalink,
                versionName: version.versionName,
                versionLabel: version.label,
                versionPath: version.path,
                isLast: version.isLast,
              });
            });
          });
        });
      });

      actions.setGlobalData({items});
      // eslint-disable-next-line no-console
      console.log(`[home-search-index] 收录 ${items.length} 篇文档`);
    },
  };
};
